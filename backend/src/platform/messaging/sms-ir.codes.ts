export function describeSmsIrStatus(status: number | undefined, remoteMessage: string | undefined): string {
  const known = status !== undefined ? STATUS_DESCRIPTIONS[status] : undefined;
  if (known && remoteMessage) return `${known} (${remoteMessage})`;
  if (known) return known;
  return remoteMessage?.trim() || 'پاسخ نامشخص از sms.ir';
}
