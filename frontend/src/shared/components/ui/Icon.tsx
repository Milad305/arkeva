export type IconName = keyof typeof ICONS;

export interface IconProps {
  name: IconName;
  /** بوم اندازه‌های ۱۰ تا ۲۸ را استفاده می‌کند؛ ۱۶ پیش‌فرض کنترل‌هاست. */
  size?: number;
  strokeWidth?: number;
  className?: string;
  /**
   * اگر آیکن تنها حامل معنا باشد (دکمهٔ بدون متن)، برچسب را روی خودِ دکمه
   * بگذار، نه اینجا. این مقدار فقط برای آیکن‌های معنادار درون متن است.
   */
  label?: string;
}

/**
 * آیکن تک‌رنگ. پیش‌فرض تزئینی است (`aria-hidden`) چون در بوم همیشه
 * متن یا `aria-label` والد معنا را می‌رساند.
 */
export function Icon({ name, size = 16, strokeWidth = 2, className, label }: IconProps) {
  const Glyph = ICONS[name];

  return (
    <Glyph
      width={size}
      height={size}
      strokeWidth={strokeWidth}
      className={className}
      style={{ flexShrink: 0, display: 'block' }}
      {...(label ? { role: 'img', 'aria-label': label } : { 'aria-hidden': true })}
    />
  );
}

/** برای جاهایی که باید وجود یک نام را در زمان اجرا بررسی کنیم (مثلاً نام آیکون از سرور). */
export function isIconName(value: string): value is IconName {
  return value in ICONS;
}
